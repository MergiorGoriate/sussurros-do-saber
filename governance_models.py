"""Private staff governance, scoped mandates and editorial collaboration records."""
from models import db, utcnow

class TeamMember(db.Model):
    removed_at = db.Column(db.DateTime, index=True)
    id = db.Column(db.Integer, primary_key=True)
    admin_id = db.Column(db.Integer, db.ForeignKey('admin_user.id'), unique=True)
    author_id = db.Column(db.Integer, db.ForeignKey('author.id'), unique=True)
    name = db.Column(db.String(180), nullable=False)
    email = db.Column(db.String(254), nullable=False)
    affiliation = db.Column(db.String(300), default='', nullable=False)
    specialty = db.Column(db.String(300), default='', nullable=False)
    orcid = db.Column(db.String(19), default='', nullable=False)
    bio = db.Column(db.Text, default='', nullable=False)
    photo = db.Column(db.String(600), default='', nullable=False)
    group = db.Column(db.String(40), default='portal', nullable=False)
    status = db.Column(db.String(30), default='invited', nullable=False)
    available = db.Column(db.Boolean, default=True, nullable=False)
    accepted_at = db.Column(db.DateTime)
    public_consent = db.Column(db.Boolean, default=False, nullable=False)
    public_visible = db.Column(db.Boolean, default=False, nullable=False)
    contact_note = db.Column(db.Text, default='', nullable=False)
    next_contact_at = db.Column(db.Date)
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)
    admin = db.relationship('AdminUser')
    author = db.relationship('Author')
    appointments = db.relationship('TeamAppointment', foreign_keys='TeamAppointment.member_id', back_populates='member')

class TeamRole(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    code = db.Column(db.String(60), unique=True, nullable=False)
    name = db.Column(db.String(160), nullable=False)
    purpose = db.Column(db.Text, default='', nullable=False)
    duties = db.Column(db.Text, default='', nullable=False)
    limits = db.Column(db.Text, default='', nullable=False)
    permissions = db.Column(db.JSON, default=list, nullable=False)

class TeamAppointment(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    member_id = db.Column(db.Integer, db.ForeignKey('team_member.id'), nullable=False, index=True)
    role_id = db.Column(db.Integer, db.ForeignKey('team_role.id'), nullable=False)
    journal_id = db.Column(db.Integer, db.ForeignKey('journal.id'))
    area = db.Column(db.String(180), default='', nullable=False)
    starts_on = db.Column(db.Date, nullable=False)
    ends_on = db.Column(db.Date)
    weekly_hours = db.Column(db.Float, default=0, nullable=False)
    conditions = db.Column(db.Text, default='', nullable=False)
    substitute_id = db.Column(db.Integer, db.ForeignKey('team_member.id'))
    active = db.Column(db.Boolean, default=True, nullable=False)
    member = db.relationship('TeamMember', foreign_keys=[member_id], back_populates='appointments')
    role = db.relationship('TeamRole')
    journal = db.relationship('Journal')
    substitute = db.relationship('TeamMember', foreign_keys=[substitute_id])

class StaffTask(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    title = db.Column(db.String(240), nullable=False)
    description = db.Column(db.Text, default='', nullable=False)
    assignee_id = db.Column(db.Integer, db.ForeignKey('team_member.id'), nullable=False, index=True)
    created_by = db.Column(db.Integer, db.ForeignKey('admin_user.id'))
    due_on = db.Column(db.Date)
    status = db.Column(db.String(30), default='pending', nullable=False)
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)
    updated_at = db.Column(db.DateTime, default=utcnow, onupdate=utcnow, nullable=False)
    assignee = db.relationship('TeamMember')

class StaffDocument(db.Model):
    removed_at = db.Column(db.DateTime, index=True)
    id = db.Column(db.Integer, primary_key=True)
    member_id = db.Column(db.Integer, db.ForeignKey('team_member.id'), nullable=False, index=True)
    title = db.Column(db.String(200), nullable=False)
    kind = db.Column(db.String(30), default='agreement', nullable=False)
    body = db.Column(db.Text, default='', nullable=False)
    filename = db.Column(db.String(180), default='', nullable=False)
    payload = db.Column(db.LargeBinary)
    accepted_at = db.Column(db.DateTime)
    accepted_by = db.Column(db.Integer, db.ForeignKey('admin_user.id'))
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)
    member = db.relationship('TeamMember')

class TaskComment(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    task_id = db.Column(db.Integer, db.ForeignKey('staff_task.id'), nullable=False, index=True)
    actor_id = db.Column(db.Integer, db.ForeignKey('admin_user.id'))
    body = db.Column(db.Text, nullable=False)
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)
    task = db.relationship('StaffTask', backref=db.backref('comments', order_by='TaskComment.id'))
    actor = db.relationship('AdminUser')

class StaffNotice(db.Model):
    researcher_id = db.Column(db.Integer, db.ForeignKey("researcher.id"), index=True)
    removed_at = db.Column(db.DateTime, index=True)
    resource_type = db.Column(db.String(40))
    resource_id = db.Column(db.Integer)
    id = db.Column(db.Integer, primary_key=True)
    admin_id = db.Column(db.Integer, db.ForeignKey('admin_user.id'), index=True)
    source_key = db.Column(db.String(180), unique=True)
    subject = db.Column(db.String(240), nullable=False)
    body = db.Column(db.Text, default='', nullable=False)
    read_at = db.Column(db.DateTime)
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)

class GovernanceAudit(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    actor_id = db.Column(db.Integer, db.ForeignKey('admin_user.id', ondelete='SET NULL'))
    actor_name = db.Column(db.String(120), nullable=False)
    action = db.Column(db.String(80), nullable=False)
    entity = db.Column(db.String(60), nullable=False)
    entity_id = db.Column(db.Integer)
    detail = db.Column(db.String(1000), default='', nullable=False)
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False, index=True)

class ArticleWorkflow(db.Model):
    article_id = db.Column(db.Integer, db.ForeignKey('article.id', ondelete='CASCADE'), primary_key=True)
    owner_id = db.Column(db.Integer, db.ForeignKey('team_member.id'), nullable=False)
    reviewer_id = db.Column(db.Integer, db.ForeignKey('team_member.id'))
    editor_id = db.Column(db.Integer, db.ForeignKey('team_member.id'))
    stage = db.Column(db.String(30), default='draft', nullable=False)
    reviewed_at = db.Column(db.DateTime)
    approved_at = db.Column(db.DateTime)
    owner = db.relationship('TeamMember', foreign_keys=[owner_id])
    reviewer = db.relationship('TeamMember', foreign_keys=[reviewer_id])
    editor = db.relationship('TeamMember', foreign_keys=[editor_id])
    article = db.relationship('Article')

class StaffPeerReview(db.Model):
    __table_args__ = (db.UniqueConstraint('manuscript_id', 'reviewer_id', 'version_number'),)
    id = db.Column(db.Integer, primary_key=True)
    manuscript_id = db.Column(db.Integer, db.ForeignKey('manuscript.id'), nullable=False, index=True)
    reviewer_id = db.Column(db.Integer, db.ForeignKey('team_member.id'), nullable=False)
    version_number = db.Column(db.Integer, nullable=False)
    assigned_by = db.Column(db.Integer, db.ForeignKey('admin_user.id'))
    status = db.Column(db.String(30), default='invited', nullable=False)
    due_on = db.Column(db.Date, nullable=False)
    conflict_declared = db.Column(db.Boolean, default=False, nullable=False)
    conflict_note = db.Column(db.Text, default='', nullable=False)
    report = db.Column(db.Text, default='', nullable=False)
    recommendation = db.Column(db.String(30), default='', nullable=False)
    submitted_at = db.Column(db.DateTime)
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)
    reviewer = db.relationship('TeamMember')
    manuscript = db.relationship('Manuscript')

class PortalReview(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    article_id = db.Column(db.Integer, db.ForeignKey('article.id'), nullable=False, index=True)
    reviewer_id = db.Column(db.Integer, db.ForeignKey('team_member.id'), nullable=False)
    action = db.Column(db.String(30), nullable=False)
    report = db.Column(db.Text, nullable=False)
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)
    reviewer = db.relationship('TeamMember')

class StaffContactLog(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    member_id = db.Column(db.Integer, db.ForeignKey('team_member.id'), nullable=False, index=True)
    actor_id = db.Column(db.Integer, db.ForeignKey('admin_user.id'))
    status = db.Column(db.String(30), nullable=False)
    note = db.Column(db.Text, nullable=False)
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)
    member = db.relationship('TeamMember', backref=db.backref('contacts', order_by='StaffContactLog.id'))
    actor = db.relationship('AdminUser')


class AuditReport(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    title = db.Column(db.String(200), nullable=False)
    snapshot = db.Column(db.JSON, default=list, nullable=False)
    created_by = db.Column(db.Integer, db.ForeignKey('admin_user.id'))
    created_at = db.Column(db.DateTime, default=utcnow, nullable=False)
    removed_at = db.Column(db.DateTime, index=True)
